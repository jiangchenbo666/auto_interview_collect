def generate_standard_answer(question: str, category: str) -> str:
    """Generate a baseline answer for one question and category."""
    base = ANSWER_TEMPLATES.get(
        category,
        "这类题建议先解释核心概念，再说明典型场景、关键步骤、常见问题和自己的实践经验。回答时要避免只背定义，最好补充一个测试或排查中的落地例子。",
    )
    return f"{base}\n\n针对“{question}”，面试回答可以按“概念 -> 方法 -> 场景 -> 风险/优化”的顺序展开。"
